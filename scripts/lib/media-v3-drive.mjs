/**
 * Drive mirror for the Part 15 candidate files.
 *
 * The manifest records every candidate as a Higgsfield CDN URL, and that CDN
 * answers 403 to this project's agent proxy — an organization policy denial,
 * not something to route around. The documented remedy was "run the script on
 * a machine with ordinary internet", which meant the 43 generated-but-unbuilt
 * rows sat in the queue indefinitely.
 *
 * The owner has since downloaded the same files to Drive, and the filenames
 * there are the CDN basenames verbatim — `hf_<date>_<time>_<jobId>.png`. That
 * is what makes the mapping exact rather than approximate: the jobId in a
 * manifest URL IS the jobId in the Drive filename, so a candidate resolves to
 * one file or to none, never to a guess.
 *
 * `docs/plan/drive-asset-map.json` holds the mapping (43 entries, 71
 * candidates, generated by matching the two lists). This module turns it into
 * a basename → download-URL lookup so `fetchBuffer` can fall back to it.
 *
 * The map is a FALLBACK, never the first choice: where the CDN is reachable it
 * stays authoritative, because it is what the manifest actually records.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "../..");
const MAP_FILE = join(ROOT, "docs/plan/drive-asset-map.json");

/** basename → Drive file id, built once on first use. */
let index = null;

function loadIndex() {
  if (index) return index;
  index = new Map();
  if (!existsSync(MAP_FILE)) return index;
  const map = JSON.parse(readFileSync(MAP_FILE, "utf8"));
  for (const entry of map.entries ?? []) {
    for (const cand of entry.candidates ?? []) {
      if (cand.file && cand.driveFileId) index.set(cand.file, cand.driveFileId);
    }
  }
  return index;
}

/**
 * `drive.google.com/uc?export=download` redirects to the same bytes but adds a
 * hop; `drive.usercontent.google.com/download` is where it lands, so ask for
 * that directly. Both require the file to be link-shared, which these are.
 */
export function driveDownloadUrl(fileId) {
  return `https://drive.usercontent.google.com/download?id=${encodeURIComponent(fileId)}&export=download`;
}

/**
 * The Drive URL mirroring a candidate URL, or null when the map does not cover
 * it — the 24 already-built assets, for instance, whose masters are committed
 * and whose candidates nobody needs again.
 */
export function driveMirrorFor(url) {
  const basename = String(url).split("/").pop();
  const fileId = loadIndex().get(basename);
  return fileId ? driveDownloadUrl(fileId) : null;
}

/** How many candidates the map covers — for the operator-facing summary. */
export function driveMirrorCount() {
  return loadIndex().size;
}
